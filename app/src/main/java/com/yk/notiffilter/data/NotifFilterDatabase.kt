package com.yk.notiffilter.data

import android.content.Context
import androidx.room.Database
import androidx.room.Room
import androidx.room.RoomDatabase
import androidx.room.TypeConverter
import androidx.room.TypeConverters
import androidx.room.migration.Migration
import androidx.sqlite.db.SupportSQLiteDatabase

class Converters {
    @TypeConverter fun verdictToString(v: Verdict?): String? = v?.name
    @TypeConverter fun stringToVerdict(s: String?): Verdict? = s?.let(Verdict::valueOf)

    @TypeConverter fun sourceToString(v: VerdictSource?): String? = v?.name
    @TypeConverter fun stringToSource(s: String?): VerdictSource? = s?.let(VerdictSource::valueOf)

    @TypeConverter fun actionToString(v: LogAction?): String? = v?.name
    @TypeConverter fun stringToAction(s: String?): LogAction? = s?.let(LogAction::valueOf)

    @TypeConverter fun modeToString(v: FilterMode?): String? = v?.name
    @TypeConverter fun stringToMode(s: String?): FilterMode? = s?.let(FilterMode::valueOf)

    @TypeConverter fun matchTargetToString(m: MatchTarget?): String? = m?.name
    @TypeConverter fun stringToMatchTarget(s: String?): MatchTarget? = s?.let(MatchTarget::valueOf)
}

@Database(
    entities = [AppRule::class, TemplateVerdict::class, LogEntry::class, NotificationRule::class],
    version = 3,
    exportSchema = true,
)
@TypeConverters(Converters::class)
abstract class NotifFilterDatabase : RoomDatabase() {
    abstract fun appRules(): AppRuleDao
    abstract fun verdicts(): TemplateVerdictDao
    abstract fun log(): LogDao
    abstract fun notificationRules(): NotificationRuleDao

    companion object {
        @Volatile private var instance: NotifFilterDatabase? = null

        /**
         * v1 → v2: the cloud classifier is gone.
         *
         * Written by hand rather than falling back to a destructive migration because
         * template_verdicts is no longer a cache — under the on-device model the rows
         * the user pinned themselves *are* the training set, and they cannot be
         * regenerated by anything but the user labelling them all again.
         *
         * Existing MODEL rows are preserved so filtering behaviour does not change
         * overnight, but they are flagged needsVerdict = 1: they came from a cloud
         * model whose reasoning nobody reviewed, so they keep filtering while waiting
         * to be confirmed, and they do not train anything until they are.
         */
        val MIGRATION_1_2 = object : Migration(1, 2) {
            override fun migrate(db: SupportSQLiteDatabase) {
                // SQLite before 3.35 cannot DROP COLUMN, and minSdk 26 ships older
                // versions, so app_rules is rebuilt rather than altered.
                db.execSQL(
                    """
                    CREATE TABLE app_rules_new (
                        packageName TEXT NOT NULL PRIMARY KEY,
                        appLabel TEXT NOT NULL,
                        mode TEXT NOT NULL,
                        enabled INTEGER NOT NULL,
                        repostKeepers INTEGER NOT NULL,
                        createdAt INTEGER NOT NULL
                    )
                    """.trimIndent()
                )
                // Apps configured under the old design were already filtering, so they
                // migrate straight to ACTIVE; sending them back to OBSERVE would
                // silently stop filtering for apps the user believes are set up.
                db.execSQL(
                    """
                    INSERT INTO app_rules_new (packageName, appLabel, mode, enabled, repostKeepers, createdAt)
                    SELECT packageName, appLabel, 'ACTIVE', enabled, repostKeepers, createdAt FROM app_rules
                    """.trimIndent()
                )
                db.execSQL("DROP TABLE app_rules")
                db.execSQL("ALTER TABLE app_rules_new RENAME TO app_rules")

                db.execSQL("ALTER TABLE template_verdicts ADD COLUMN needsVerdict INTEGER NOT NULL DEFAULT 0")
                db.execSQL("ALTER TABLE template_verdicts ADD COLUMN score REAL NOT NULL DEFAULT 0.0")
                // Old rows have no channel recorded; they still train on their words
                // and shape features, just without the channel signal.
                db.execSQL("ALTER TABLE template_verdicts ADD COLUMN channelId TEXT NOT NULL DEFAULT ''")
                db.execSQL("UPDATE template_verdicts SET needsVerdict = 1 WHERE source = 'MODEL'")
                db.execSQL(
                    "CREATE INDEX IF NOT EXISTS index_template_verdicts_needsVerdict " +
                        "ON template_verdicts (needsVerdict)"
                )
            }
        }

        /**
         * v2 → v3: Add notification_rules table for deterministic Whitelist/Blacklist matching.
         */
        val MIGRATION_2_3 = object : Migration(2, 3) {
            override fun migrate(db: SupportSQLiteDatabase) {
                db.execSQL(
                    """
                    CREATE TABLE IF NOT EXISTS notification_rules (
                        id INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL,
                        packageName TEXT,
                        pattern TEXT NOT NULL,
                        isRegex INTEGER NOT NULL,
                        matchTarget TEXT NOT NULL,
                        verdict TEXT NOT NULL,
                        enabled INTEGER NOT NULL,
                        description TEXT,
                        createdAt INTEGER NOT NULL
                    )
                    """.trimIndent()
                )
                db.execSQL(
                    "CREATE INDEX IF NOT EXISTS index_notification_rules_packageName " +
                        "ON notification_rules (packageName)"
                )
                db.execSQL(
                    "CREATE INDEX IF NOT EXISTS index_notification_rules_verdict " +
                        "ON notification_rules (verdict)"
                )
                db.execSQL(
                    "CREATE INDEX IF NOT EXISTS index_notification_rules_enabled " +
                        "ON notification_rules (enabled)"
                )
            }
        }

        fun get(context: Context): NotifFilterDatabase = instance ?: synchronized(this) {
            instance ?: Room.databaseBuilder(
                context.applicationContext,
                NotifFilterDatabase::class.java,
                "notiffilter.db",
            ).addMigrations(MIGRATION_1_2, MIGRATION_2_3).build().also { instance = it }
        }
    }
}
